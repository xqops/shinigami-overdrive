// Embeds the sound bank (assets/sounds/*.mp3, made by tools/fetch-sounds.js) into
// src/assets/sounds.js as base64, so the game still opens from file:// with no server.
// Usage: node tools/embed-sounds.js
'use strict';
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const dir = path.join(root, 'assets', 'sounds');
const out = {};
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.mp3')).sort()) {
  out[f.slice(0, -4)] = fs.readFileSync(path.join(dir, f)).toString('base64');
}
const js = '// GENERATED by tools/embed-sounds.js from assets/sounds/. Do not edit by hand.\n' +
  'window.SO_SOUNDS = ' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(root, 'src', 'assets', 'sounds.js'), js);
console.log(Object.keys(out).length + ' sounds, src/assets/sounds.js ' + (js.length / 1024).toFixed(0) + ' KB');
