// Embeds the ability icons (assets/icons/<id>.jpg, cropped from the design sheet by
// tools/crop-icons.sh) into src/assets/icons.js as data URIs, so the game opens from file://.
// Usage: node tools/embed-icons.js
'use strict';
const fs = require('fs'), path = require('path');

const root = path.join(__dirname, '..');
const dir = path.join(root, 'assets', 'icons');
const icons = {};
for (const f of fs.readdirSync(dir).sort()) {
  if (f.endsWith('.jpg')) icons[f.slice(0, -4)] = 'data:image/jpeg;base64,' + fs.readFileSync(path.join(dir, f)).toString('base64');
}
const js = '// GENERATED by tools/embed-icons.js from assets/icons/. Do not edit by hand.\n' +
  'window.SO_ICONS = ' + JSON.stringify(icons) + ';\n';
fs.writeFileSync(path.join(root, 'src', 'assets', 'icons.js'), js);
console.log(Object.keys(icons).length + ' icons, src/assets/icons.js', (js.length / 1024).toFixed(0) + ' KB');
