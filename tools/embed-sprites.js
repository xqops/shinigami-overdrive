// Embeds every PNG under assets/sprites/ into src/assets/sprites.js as raw RGBA pixels, so the
// game can build voxel models synchronously and still open from file:// with no server.
// Usage: node tools/embed-sprites.js
'use strict';
const fs = require('fs'), path = require('path'), zlib = require('zlib');

const root = path.join(__dirname, '..');
const srcDir = path.join(root, 'assets', 'sprites');

// Minimal PNG decoder: 8-bit RGB/RGBA, non-interlaced (what canvas.toDataURL produces).
function decodePNG(buf) {
  let pos = 8, w = 0, h = 0, colorType = 0, bitDepth = 0;
  const idat = [];
  while (pos < buf.length) {
    const len = buf.readUInt32BE(pos), type = buf.toString('ascii', pos + 4, pos + 8), data = buf.slice(pos + 8, pos + 8 + len);
    if (type === 'IHDR') { w = data.readUInt32BE(0); h = data.readUInt32BE(4); bitDepth = data[8]; colorType = data[9]; if (data[12]) throw new Error('interlaced PNG not supported'); }
    else if (type === 'IDAT') idat.push(data);
    else if (type === 'IEND') break;
    pos += 12 + len;
  }
  if (bitDepth !== 8 || (colorType !== 6 && colorType !== 2)) throw new Error('unsupported PNG format');
  const bpp = colorType === 6 ? 4 : 3, stride = w * bpp;
  const raw = zlib.inflateSync(Buffer.concat(idat));
  const out = Buffer.alloc(w * h * 4);
  let prev = Buffer.alloc(stride);
  for (let y = 0; y < h; y++) {
    const f = raw[y * (stride + 1)];
    const line = Buffer.from(raw.slice(y * (stride + 1) + 1, (y + 1) * (stride + 1)));
    for (let x = 0; x < stride; x++) {
      const a = x >= bpp ? line[x - bpp] : 0, b = prev[x], c = x >= bpp ? prev[x - bpp] : 0;
      let v = line[x];
      if (f === 1) v += a; else if (f === 2) v += b; else if (f === 3) v += (a + b) >> 1;
      else if (f === 4) { const p = a + b - c, pa = Math.abs(p - a), pb = Math.abs(p - b), pc = Math.abs(p - c); v += pa <= pb && pa <= pc ? a : pb <= pc ? b : c; }
      line[x] = v & 255;
    }
    for (let x = 0; x < w; x++) {
      out[(y * w + x) * 4] = line[x * bpp]; out[(y * w + x) * 4 + 1] = line[x * bpp + 1]; out[(y * w + x) * 4 + 2] = line[x * bpp + 2];
      out[(y * w + x) * 4 + 3] = bpp === 4 ? line[x * bpp + 3] : 255;
    }
    prev = line;
  }
  return { w, h, px: out.toString('base64') };
}

const sprites = {};
(function walk(dir, prefix) {
  for (const f of fs.readdirSync(dir).sort()) {
    const full = path.join(dir, f);
    if (fs.statSync(full).isDirectory()) walk(full, prefix + f + '/');
    else if (f.endsWith('.png')) sprites[prefix + f.slice(0, -4)] = decodePNG(fs.readFileSync(full));
  }
})(srcDir, '');

fs.mkdirSync(path.join(root, 'src', 'assets'), { recursive: true });
const js = '// GENERATED by tools/embed-sprites.js from assets/sprites/. Do not edit by hand.\n' +
  'window.SO_SPRITES = ' + JSON.stringify(sprites) + ';\n';
fs.writeFileSync(path.join(root, 'src', 'assets', 'sprites.js'), js);
console.log(Object.keys(sprites).map((k) => `${k} ${sprites[k].w}x${sprites[k].h}`).join('\n'));
console.log('src/assets/sprites.js', (js.length / 1024).toFixed(0) + ' KB');
