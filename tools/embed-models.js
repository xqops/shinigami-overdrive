// Embeds the rigged models into src/assets/models.js as base64, so the game still opens from
// file:// with no server: enemies (assets/models/enemies/*.glb, made by tools/blender/rig_enemy.py)
// and the first-person arms (assets/models/player/arms.glb, made by tools/blender/prep_arms.py).
// Usage: node tools/embed-models.js
'use strict';
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const out = {};
for (const [sub, prefix] of [['enemies', ''], ['player', 'player_']]) {
  const dir = path.join(root, 'assets', 'models', sub);
  if (!fs.existsSync(dir)) continue;
  // *_source_* files are the untouched downloads kept for provenance, not game assets
  for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.glb') && !f.includes('_source')).sort()) {
    out[prefix + f.slice(0, -4)] = fs.readFileSync(path.join(dir, f)).toString('base64');
  }
}
const js = '// GENERATED by tools/embed-models.js from assets/models/. Do not edit by hand.\n' +
  'window.SO_MODELS = ' + JSON.stringify(out) + ';\n';
fs.mkdirSync(path.join(root, 'src', 'assets'), { recursive: true });
fs.writeFileSync(path.join(root, 'src', 'assets', 'models.js'), js);
console.log(Object.keys(out).join(', '));
console.log('src/assets/models.js', (js.length / 1024 / 1024).toFixed(2) + ' MB');
